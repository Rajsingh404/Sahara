"""Write docs/evaluation_report.md from the selected run's recorded results (no hand-typed numbers).

Reads models/logs/<run>/{metrics.json, class_thresholds.json, test_metrics.json, false_alarms.json,
export_validation.json} and models/logs/runs_summary.csv. Missing parts are reported as "not run".

    python scripts/write_evaluation_report.py [--run <run folder>]
"""
from __future__ import annotations

import argparse
import csv
import json
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.config import MODELS_DIR, REPO_ROOT, SAFETY_CRITICAL_CLASSES, SOUND_CLASSES
from src.evaluation.streaming import selected_run_dir

DOC = REPO_ROOT / "docs" / "evaluation_report.md"
SET_TITLES = {
    "public": "Public test set (FSD50K, AudioSet, ESC-50 targets; DESED, ESC-50, FSD50K background)",
    "indian_team": "Indian team test set (team phone recordings, ~40 % of each label; self-recorded)",
    "synthetic": "Synthetic test set (test clips mixed onto test background, −5 to +10 dB): SYNTHETIC, not real-world",
}


def _load(path: Path):
    return json.loads(path.read_text()) if path.exists() else None


def _f(v, digits=3):
    return "–" if v is None else f"{v:.{digits}f}"


def build(run: str | None = None) -> str:
    run_dir = selected_run_dir(run)
    rel = run_dir.relative_to(REPO_ROOT)
    val = _load(run_dir / "metrics.json")
    thr = _load(run_dir / "class_thresholds.json")
    test = _load(run_dir / "test_metrics.json")
    fa = _load(run_dir / "false_alarms.json")
    exp = _load(run_dir / "export_validation.json")
    cfg = _load(run_dir / "config.json")
    out = [
        "# SAHARA Evaluation Report", "",
        f"Generated by `scripts/write_evaluation_report.py` from run **`{run_dir.name}`** "
        f"(`{rel}/`). Every number below is read from that folder; nothing is typed by hand.", "",
        f"- Git SHA at training: `{cfg['git_sha'] if cfg else '–'}`",
        "- Model: frozen YAMNet → Dense head 256 → 128 → 8 sigmoid, weighted BCE, class-balanced sample weights.",
        "- Input: the phone's window vector (mean of the last two non-silent 0.5 s hop embeddings of raw mic audio), "
        "reproduced exactly in Python (`tests/test_windowing.py`, max difference 0.0).",
        "- Selection: best validation *policy score* (weighted share of validation clips that raise the right alert "
        "with thresholds and hits tuned to the false-alarm budget) with the safety precision floor met "
        "(`scripts/compare_runs.py`); thresholds tuned on validation only; test data used once, for this report.", "",
    ]

    out += ["## Validation (model selection)", ""]
    if val:
        out += [f"Validation mAP **{val['val_mAP']:.3f}** on {val['val_windows']} windows (best epoch {val['best_epoch']}). "
                f"Source: `{rel}/metrics.json`.", ""]
    summary = MODELS_DIR / "logs" / "runs_summary.csv"
    if summary.exists():
        with summary.open(newline="", encoding="utf-8") as handle:
            all_rows = list(csv.DictReader(handle))
        rows = sorted((r for r in all_rows if r.get("same_val_data") == "True"),
                      key=lambda r: -float(r.get("policy_score") or 0))
        older = len(all_rows) - len(rows)
        out += ["Runs scored on the current validation set (`models/logs/runs_summary.csv`; "
                f"{older} earlier runs used a previous dataset build and are not comparable):", "",
                "| Run | Policy score | Val mAP | Synthetic | Fine-tuned from | Features | Safety floor |",
                "|---|---:|---:|---|---|---|---|"]
        for r in rows:
            mark = " **(selected)**" if r["run"] == run_dir.name else ""
            ps = f"{float(r['policy_score']):.3f}" if r.get("policy_score") else "–"
            out.append(f"| `{r['run']}`{mark} | {ps} | {float(r['val_mAP']):.3f} | {r['synthetic']} | {r['finetune_from'] or '–'} | "
                       f"{r['features']} | {'met' if r['safety_floor_met'] == 'True' else 'missed'} |")
        out.append("")

    out += ["## Alert settings (tuned on validation against a false-alarm budget)", ""]
    if thr and "hits_required" in thr.get(SOUND_CLASSES[0], {}):
        meta = thr["_meta"]
        out += [f"`data/metadata/class_thresholds.json` (copy in `{rel}/class_thresholds.json`), from "
                "`src/evaluation/tune_policy.py`. Each class gets a threshold and how many of the last 3 windows must "
                "clear it; together they maximise the weighted share of validation clips that raise the right alert, "
                f"with total false alarms on validation audio without that sound ≤ **{meta['false_alarm_budget_per_hour']} "
                f"per hour** (reached: {meta['val_total_false_alarms_per_hour']}/h over {meta['val_clips']} validation clips).",
                "", "| Class | Threshold | Windows needed (of 3) | Val clips alerted | Val false alarms/h |",
                "|---|---:|---:|---:|---:|"]
        for c in SOUND_CLASSES:
            t = thr[c]
            out.append(f"| {c} | {t['threshold']:.3f} | {t['hits_required']} | {t['val_clip_detection']:.3f} "
                       f"({t['val_clips']} clips) | {t['val_false_alarms_per_hour']:.2f} |")
        out.append("")
        tuning = _load(run_dir / "policy_tuning.json")
        if tuning:
            out += ["Detection vs false-alarm budget on validation (same model; how the budget was chosen):", "",
                    "| Budget (alerts/h) | Reached | Mean share of clips alerted |", "|---:|---:|---:|"]
            for row in tuning["tradeoff"]:
                out.append(f"| {row['budget_per_hour']} | {row['total_fa_per_hour']} | {row['mean_detection']:.3f} |")
            out.append("")
    elif thr:
        out += ["Window-level thresholds (older format).", ""]

    out += ["## Test results", ""]
    if not test:
        out += ["Not run yet.", ""]
    else:
        out += ["Window metrics use the tuned thresholds. *Clip detection* plays each test clip through the app's alert "
                "policy (2 of 3 windows, 1 hit for safety-critical classes, 10 s cooldown) and counts clips that raise "
                "the right alert. Source: `" + f"{rel}/test_metrics.json" + "`.", ""]
        for name, title in SET_TITLES.items():
            s = test["sets"].get(name)
            if not s:
                out += [f"### {title}", "", "Not available.", ""]
                continue
            cd = s["clip_detection_with_app_policy"]
            out += [f"### {title}", "",
                    f"mAP **{_f(s['mAP'])}** over {len(s['classes_in_mAP'])} classes present; {s['windows']} windows "
                    f"({s['background_windows']} background).", "",
                    "| Class | AP | Precision | Recall | F1 | Positive windows | Clips detected |",
                    "|---|---:|---:|---:|---:|---:|---:|"]
            for c in SOUND_CLASSES:
                m = s["per_class"].get(c)
                if not m:
                    out.append(f"| {c} | – | – | – | – | 0 | no test clips |")
                    continue
                d = cd.get(c, {})
                out.append(f"| {c} | {m['ap']:.3f} | {m['precision']:.3f} | {m['recall']:.3f} | {m['f1']:.3f} | "
                           f"{m['positive_windows']} | {d.get('detected', 0)}/{d.get('clips', 0)} |")
            wrong = cd.get("_wrong_class_alerts", {})
            out += ["", f"Wrong-class alerts while playing target clips: "
                        f"{', '.join(f'{k} {v}' for k, v in sorted(wrong.items(), key=lambda kv: -kv[1])) or 'none'}.",
                    f"Confusion matrix: `{rel}/confusion_test_{name}.png`.", ""]

    out += ["## False alarms per hour (test background, app policy)", ""]
    if not fa:
        out += ["Not run yet.", ""]
    else:
        out += ["Test-split background clips played back to back through VAD → pool → head → policy. "
                f"Source: `{rel}/false_alarms.json`.", "",
                "| Background set | Clips | Hours | False alarms | Per hour | Main classes |", "|---|---:|---:|---:|---:|---|"]
        for name, r in fa["sets"].items():
            top = sorted(r["per_class"].items(), key=lambda kv: -kv[1]["count"])[:3]
            main = ", ".join("%s %d" % (c, v["count"]) for c, v in top if v["count"]) or "–"
            out.append(f"| {name} | {r['clips']} | {r['hours']:.2f} | {r['false_alarms']} | "
                       f"{_f(r['false_alarms_per_hour'], 1)} | {main} |")
        out.append("")

    out += ["## Indian team recordings: 5-fold cross-validation", ""]
    cv = _load(run_dir / "team_cv.json")
    if cv:
        out += [f"All {cv['team_clips']} team clips are tested once by a model that never heard them "
                f"(`{rel}/team_cv.json`, mode `{cv['mode']}`, team weight ×{cv['team_weight']}). *Without team data* = "
                "the same recipe trained on public data only.", "",
                "| Class | AP without team data | AP with team data | Clips alerted without | Clips alerted with |",
                "|---|---:|---:|---:|---:|"]
        for c in SOUND_CLASSES:
            b, f = cv["base"]["per_class"].get(c), cv["finetuned"]["per_class"].get(c)
            if not b:
                out.append(f"| {c} | – | – | no team clips | – |")
                continue
            out.append(f"| {c} | {b['ap']:.3f} | {f['ap']:.3f} | {b['detected']}/{b['clips']} | {f['detected']}/{f['clips']} |")
        out += ["", f"mAP {cv['base']['mAP']:.3f} → {cv['finetuned']['mAP']:.3f}. Team background "
                f"({cv['finetuned']['background_clips']} clips, {cv['finetuned']['background_hours'] * 60:.1f} min): "
                f"{cv['base']['background_false_alarms']} → {cv['finetuned']['background_false_alarms']} false alarms.", ""]
    else:
        out += ["Not run yet.", ""]

    out += ["## Export (TFLite)", ""]
    if exp:
        out += [f"FP32 head vs Keras on {exp['test_windows']} test windows: max |diff| {exp['fp32_max_abs_diff']:.2e} "
                f"({'pass' if exp['fp32_pass'] else 'FAIL'}, limit 1e-4). INT8 mAP {exp['int8_mAP']:.4f} vs Keras "
                f"{exp['keras_mAP']:.4f}: drop {exp['int8_mAP_drop']:.4f} ({'pass' if exp['int8_pass'] else 'FAIL'}, limit 0.02). "
                f"Sizes (KiB): {', '.join(f'{k} {v}' for k, v in exp['sizes_kib'].items())}. Source: `{rel}/export_validation.json`.", ""]
    else:
        out += ["Not run yet (Phase 5).", ""]
    app_check = _load(run_dir / "app_pipeline_check.json")
    if app_check:
        out += ["**Shipped in `app/assets/`: the FP32 head** (1.2 MB) with `yamnet.tflite` (12.6 MB). The alert thresholds "
                "were tuned on full-precision scores and several sit at 0.93–0.98, where INT8's score changes (up to "
                f"{exp['int8_max_abs_diff']:.3f}) could move alerts; the INT8 saving (~0.9 MB) is not worth that risk."
                if exp else "**Shipped in `app/assets/`: the FP32 head** with `yamnet.tflite`.",
                "",
                f"End-to-end check (`app/tool/check_app_pipeline.py`): {app_check['clips']} test clips replayed through exactly "
                "what the app runs (16-bit PCM → 1 s ring buffer → VAD → `yamnet.tflite` → embedding pool → "
                "`sahara_classifier.tflite` → alert policy with the bundled settings) raise the same alerts as the evaluation "
                f"pipeline in **{app_check['same_alerts']}/{app_check['clips']}** clips; max score difference "
                f"{app_check['max_score_diff']:.4f}. Source: `{rel}/app_pipeline_check.json`.", ""]

    out += ["## On-device measurements (Phase 6)", ""]
    phone_files = sorted((MODELS_DIR / "logs" / "phone").glob("*.json"))
    if phone_files:
        ph = _load(phone_files[-1])
        ms = ph["inference_ms_per_window"]
        pb = ph["speaker_playback_test"]
        out += [f"{ph['device']['model']}, Android {ph['device']['android']}, {ph['date']} "
                f"(`{phone_files[-1].relative_to(REPO_ROOT)}`). {ph['provenance']}", "",
                "| Check | Result |", "|---|---|"]
        for k, v in ph["checks"].items():
            out.append(f"| {k.replace('_', ' ')} | {v} |")
        out += ["", f"Inference per window (YAMNet + head, CPU): {ms['screen_on']['avg_range'][0]}–"
                f"{ms['screen_on']['avg_range'][1]} ms average with the screen on (max {ms['screen_on']['max']} ms), "
                f"{ms['screen_off']['avg_range'][0]}–{ms['screen_off']['avg_range'][1]} ms with it off (max "
                f"{ms['screen_off']['max']} ms); a window is processed every 500 ms. Memory (debug build): "
                f"{ph['memory']['debug_build_total_pss_mb']} MB PSS.", "",
                f"Speaker playback ({pb['method']}):", ""]
        for run, r in pb["runs"].items():
            out.append(f"- {run.replace('_', ' ')}: alerted {', '.join(r['alerted'])}; missed {', '.join(r['missed'])}.")
        out += ["", pb["interpretation"], "",
                "Latency from the start of the played clip: " + ", ".join(f"{k} {v} s" for k, v in pb["latency_s_from_clip_start_run2"].items())
                + ". " + pb["latency_note"], "",
                "Not measured yet: " + "; ".join(f"{k.replace('_', ' ')} ({v})" for k, v in ph["not_measured"].items()) + ".", ""]
    else:
        out += ["Not measured yet (needs the test phone).", ""]

    out += ["## Personalization (Phase 7)", ""]
    pers = MODELS_DIR / "logs" / "personalization"
    aryan, custom = _load(pers / "aryan_eval.json"), _load(pers / "custom_sounds_eval.json")
    if aryan and custom:
        a5, a10 = aryan["shots"]["5"], aryan["shots"]["10"]
        out += ["Few-shot prototypes over the same YAMNet window vectors (`src/personalization/`), centred on the mean "
                "background window; threshold set on the train side so validation background gives ≤ "
                f"{aryan['budget_per_hour']} alert/h; {aryan['rounds']} random enrolments each. Sources: "
                "`models/logs/personalization/aryan_eval.json`, `custom_sounds_eval.json`.", "",
                "| Enrolled sound | Clips alerted (test) | Other names accepted | Background alerts/h | EER vs other names | EER vs background |",
                "|---|---:|---:|---:|---:|---:|"]
        for k, v in (("5", a5), ("10", a10)):
            sm = v["summary"]
            out.append(f"| \"Aryan\" (team recordings), {k} samples | {sm['test_detection']['mean']:.0%} | "
                       f"{sm['test_other_name_accepts']['mean']:.0%} | {sm['test_background_alerts_per_hour']['mean']:.2f} | "
                       f"{sm['test_eer_name_vs_other_names']['mean']:.2f} | {sm['test_eer_name_vs_background_clips']['mean']:.2f} |")
        out += ["", "| Household sound (FSD50K, 5 samples) | Test clips | Clips alerted | Background alerts/h | EER vs background |",
                "|---|---:|---:|---:|---:|"]
        for name, v in custom["sounds"].items():
            out.append(f"| {name.replace('_', ' ')} | {v['test_clips']} | {v['detection']:.0%} | "
                       f"{v['background_alerts_per_hour']:.2f} | {v['eer_vs_background_clips']:.2f} |")
        out += ["", "**Finding.** A name is not distinguishable from other names: other names score higher than \"Aryan\" "
                f"(mean similarity {a5['mean_scores']['other_names']:.2f} vs {a5['mean_scores']['aryan']:.2f}); YAMNet "
                "describes kinds of sound, not words. A name call versus background does separate (EER "
                f"{a5['summary']['test_eer_name_vs_background_clips']['mean']:.2f}). Household sounds separate from background to "
                "varying degrees (toilet flush perfectly), but at a strict 1 alert/h few test clips alert, partly because each "
                "\"sound\" here is a category recorded by many people; one user's own appliance repeats far more consistently. "
                "The app therefore offers custom sounds as experimental and for distinctive household sounds, not names.", ""]
    else:
        out += ["Not run yet.", ""]

    out += ["## Wristband (Phase 8)", "",
            "Not tested on hardware: no wristband parts were available. The firmware builds (`pio run`), and the app's "
            "BLE packet format is unit-tested against `docs/ble_protocol.md`; phone-to-buzz latency, current draw and "
            "battery life are not measured.", ""]

    out += ["## Known limitations", "",
            "- Window-level metrics count 0.5 s windows, so long clips weigh more than short ones; clip detection is the closer "
            "proxy for what a user experiences.",
            "- The Indian team test set is small (a few clips per class) and split per label, so the same phone or room "
            "can appear in train and test; there are no team recordings of smoke_alarm, siren or glass_break.",
            "- knocking, appliance_beep and doorbell have the lowest test AP; their detection is limited by the model, "
            "not the alert settings (see the budget trade-off above).",
            "- Synthetic results are reported separately and never as real-world performance.",
            f"- Safety-critical classes ({', '.join(SAFETY_CRITICAL_CLASSES)}) alert on a single window; their false alarms "
            "are listed above.", ""]

    out += ["## Superseded results (do not quote)", "",
            "These earlier figures were produced before Phase 1–3 fixes, on small samples, with no recorded run folder or "
            "checkpoint in the repo. They used whole-clip mean features and label maps later found to be wrong "
            "(see `docs/dataset_card.md`), so they are not comparable with the numbers above.", "",
            "| Figure | Where it appeared | Why superseded |", "|---|---|---|",
            "| mAP 0.618 | handoff notes / CLAUDE.md | ~171 AudioSet clips; no run record |",
            "| mAP 0.651 | `docs/dataset_card.md` (2026-08-28 baseline) | 64 of 188 AudioSet clips mislabelled; FSD50K `Alarm` as appliance_beep; test split could leak multi-label clips |",
            "| macro AP 0.783 | previous `docs/evaluation_report.md` | test classes of 3–7 clips at threshold 0.5; no run record |",
            "| val mAP 0.913 and other Phase 3 runs of 2026-10-04 | Phase 3 summary | scored with Keras `predict()` on the Metal GPU, which returns wrong scores (see `src/models/classifier_head.py`); earlier dataset build |",
            ""]
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--run")
    args = parser.parse_args()
    DOC.write_text(build(args.run), encoding="utf-8")
    cm = selected_run_dir(args.run) / "confusion_test_public.png"
    if cm.exists():
        shutil.copyfile(cm, REPO_ROOT / "docs" / "confusion_matrix.png")
    print(f"Wrote {DOC}")


if __name__ == "__main__":
    main()
